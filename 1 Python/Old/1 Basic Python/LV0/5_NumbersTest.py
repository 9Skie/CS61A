cool_number = -2
print("-2 to the power of 3 is " + "[" + str(pow(cool_number, 3)) + "]")
print("the absolute value of -2 is " + "[" + str(abs(cool_number)) + "]")
print("the bigger number between -2 and 5 is " + "[" + str(max(cool_number, 5)) + "]")
print("the smaller number between -2 and 2 is " + "[" + str(min(cool_number, 2)) + "]")
print(round(cool_number + 1.2))